def format_itinerary_ready(
    trip: Trip, itinerary: Itinerary, language: Language | str = "en"
) -> NotificationMessage:
    """The "itinerary ready" message (or "generation failed" when ``status == "error"``)."""
    lang = language if language in TEXT else "en"
    city = _destination_city(trip, lang)
    url = app_url(f"/itineraries/{itinerary.id}")  # SPA route (DESIGN §7)
    data: dict[str, Any] = {
        "kind": "itinerary",
        "language": lang,
        "trip_id": trip.id,
        "itinerary_id": itinerary.id,
        "status": itinerary.status,
    }
    if itinerary.status == "error":
        body = _t(lang, "itinerary_failed", city=city)
        if itinerary.error:
            body += f"\n\n{itinerary.error}"
        return NotificationMessage(
            title=_t(lang, "itinerary_failed_title"),
            body=body,
            url=url,
            url_label=_t(lang, "open_itinerary"),
            data=data | {"summary": _t(lang, "itinerary_failed", city=city)},
        )

    plan = itinerary.plan or {}
    blocks = [_t(lang, "itinerary_ready", city=city)]
    details = [str(plan["title"])] if plan.get("title") else []
    start = _parse_date(itinerary.arrival_at) or trip.depart_date
    end = _parse_date(itinerary.departure_at) or trip.return_date
    days = len(plan.get("days") or []) or ((end - start).days + 1 if start and end else 0)
    dates = format_date_range(start, end, lang)
    if dates and days:
        key = "itinerary_one_day" if days == 1 else "itinerary_days"
        details.append(_t(lang, key, dates=dates, n=days))
    cost = _budget_line(plan.get("budget") or {}, lang)
    if cost:
        details.append(cost)
    generator = "generator_claude" if itinerary.generator == "claude" else "generator_rule_based"
    details.append(_t(lang, "generator", generator=_t(lang, generator)))
    blocks.append("\n".join(details))
    return NotificationMessage(
        title=_t(lang, "itinerary_title"),
        body="\n\n".join(blocks),
        url=url,
        url_label=_t(lang, "open_itinerary"),
        data=data | {"summary": "\n".join([blocks[0], *details[:2]])},
    )


def _budget_line(budget: dict[str, Any], language: str) -> str:
    total = budget.get("total_estimated")
    currency = budget.get("currency")
    if not isinstance(total, (int, float)) or not currency:
        return ""
    line = _t(language, "itinerary_cost", amount=format_amount(float(total), str(currency)))
    within = budget.get("within_budget")
    if isinstance(within, bool):
        line += f" ({_t(language, 'within_budget' if within else 'over_budget')})"
    return line


def format_test_message(language: Language | str = "en") -> NotificationMessage:
    """A short message for the per-channel "send test" button in Settings."""
    lang = language if language in TEXT else "en"
    when = now_local().strftime("%Y-%m-%d %H:%M")
    return NotificationMessage(
        title=_t(lang, "test_title"),
        body=f"{_t(lang, 'test_body')}\n{_t(lang, 'test_sent_at', when=when)}",
        url=app_url("/settings"),
        url_label=_t(lang, "open_settings"),
        data={
            "kind": "system",
            "test": True,
            "language": lang,
            "summary": _t(lang, "test_summary"),
        },
    )
