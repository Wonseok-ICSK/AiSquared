def _t(language: str, key: str, **kwargs: Any) -> str:
    table = TEXT.get(language, TEXT["en"])
    return table[key].format(**kwargs) if kwargs else table[key]


# --------------------------------------------------------------------------- primitives


def format_amount(amount: float, currency: str) -> str:
    """``"KRW 278,000"``; two decimals only for currencies with minor units and a fraction."""
    code = (currency or "").upper()
    if code in _ZERO_DECIMAL_CURRENCIES or abs(amount - round(amount)) < _EPSILON:
        return f"{code} {round(amount):,}".strip()
    return f"{code} {amount:,.2f}".strip()


def format_date(value: date, language: str = "en") -> str:
    """``"Nov 20"`` (en) / ``"11월 20일"`` (ko), independent of the OS locale."""
    month = _MONTHS_EN[value.month - 1] if language != "ko" else value.month
    return _t(language, "date", month=month, day=value.day)


def format_date_range(start: date | None, end: date | None, language: str = "en") -> str:
    """``"Nov 20 – Nov 23"``, or a single date for one-way trips."""
    if start is None:
        return format_date(end, language) if end else ""
    if end is None or end == start:
        return format_date(start, language)
    return f"{format_date(start, language)} – {format_date(end, language)}"


def city_name(code: str, language: str = "en") -> str | None:
    """City of an airport/metro code (``NRT`` -> ``Tokyo`` / ``도쿄``), ``None`` if unknown."""
    normalized = (code or "").strip().upper()
    if language == "ko":
        korean = _korean_city(normalized)
        if korean:
            return korean
    info = city_info(normalized) if normalized else None
    return str(info["city"]) if info else None


def _korean_city(code: str) -> str | None:
    metro_code = code if code in METRO_CODES else metro_for_airport(code)
    aliases = METRO_CODES[metro_code].aliases if metro_code else AIRPORT_ALIASES.get(code, ())
    return aliases[0] if aliases else None


def _place(codes: Sequence[str], language: str) -> str:
    unique = [c for c in dict.fromkeys(c.upper() for c in codes if c)]
    if not unique:
        return "?"
    city = city_name(unique[0], language)
    joined = "/".join(unique)
    return f"{city} ({joined})" if city else joined


def _parse_date(value: Any) -> date | None:
    if isinstance(value, date):
        return value
    if isinstance(value, str) and len(value) >= 10:
        try:
            return date.fromisoformat(value[:10])
        except ValueError:
            return None
    return None


def _clock(value: str | None) -> str:
    return value[11:16] if value and len(value) >= 16 else ""


def _convert_basis(value: float, src: str, dst: str, adults: int) -> float:
    if src == dst:
        return value
    return value * adults if dst == "total" else value / adults


def _pct(value: float) -> str:
    return f"{value:.1f}"


# --------------------------------------------------------------------------- price alert


class _AlertFacts:
    """Values shown in a price alert, all in the display basis and currency."""

    def __init__(
        self,
        trip: Trip,
        run: SearchRun | None,
        offer: FlightOffer | None,
        events: Sequence[AlertEvent],
        previous_lowest: float | None,
    ) -> None:
        self.adults = max(int(trip.adults or 1), 1)
        self.basis: PriceBasis = "total" if trip.price_basis == "total" else "per_person"
        self.events = sorted(events, key=lambda e: _KIND_ORDER.get(e.kind, 9))
        self.currency = (
            (offer.currency if offer else None)
            or (self.events[0].currency if self.events else None)
            or (run.currency if run else None)
            or trip.currency
            or ""
        ).upper()
        self.price = self._current_price(offer)
        self.previous_lowest = (
            previous_lowest if previous_lowest is not None else self._from_events("previous_lowest")
        )
        self.target = self._target(trip)
        self.drop_percent = self._drop_percent()

    def _event_value(self, event: AlertEvent, value: float | None) -> float | None:
        if value is None or event.currency.upper() != self.currency:
            return None
        return _convert_basis(value, event.basis, self.basis, self.adults)

    def _current_price(self, offer: FlightOffer | None) -> float | None:
        if offer is not None:
            return offer.price_total if self.basis == "total" else offer.price_per_person
        for event in self.events:
            value = self._event_value(event, event.price)
            if value is not None:
                return value
        return None

    def _from_events(self, attr: str) -> float | None:
        for event in self.events:
            value = self._event_value(event, getattr(event, attr))
            if value is not None:
                return value
        return None

    def _target(self, trip: Trip) -> float | None:
        for event in self.events:
            if event.kind == "below_target":
                value = self._event_value(event, event.threshold)
                if value is not None:
                    return value
        if trip.target_price is not None and (trip.currency or "").upper() == self.currency:
            return trip.target_price
        return None

    def _drop_percent(self) -> float | None:
        for event in self.events:
            if event.kind != "price_drop":
                continue
            if event.drop_percent is not None:
                return event.drop_percent
            if event.previous_price and event.previous_price > 0:
                return (event.previous_price - event.price) / event.previous_price * 100
        return None


def _amount_text(value: float, facts: _AlertFacts, language: str) -> str:
    amount = format_amount(value, facts.currency)
    if facts.adults <= 1:
        return amount
    note = (
        _t(language, "per_person")
        if facts.basis == "per_person"
        else _t(language, "total", n=facts.adults)
    )
    return _t(language, "amount_note", amount=amount, note=note)


def _route_line(trip: Trip, offer: FlightOffer | None, language: str) -> tuple[str, str]:
    """``("Seoul (ICN) ↔ Tokyo (NRT)", "ICN ↔ NRT")`` using the offer's actual airports."""
    if offer is None:
        origins, destinations = [trip.origin], [trip.destination]
        round_trip = trip.trip_type == "round_trip"
    else:
        inbound = offer.inbound or {}
        origins = [offer.departure_airport, inbound.get("arrival_airport", "")]
        destinations = [offer.arrival_airport, inbound.get("departure_airport", "")]
        round_trip = bool(inbound) or offer.return_date is not None
    arrow = "↔" if round_trip else "→"
    full = f"{_place(origins, language)} {arrow} {_place(destinations, language)}"
    short = f"{'/'.join(dict.fromkeys(c for c in origins if c))} {arrow} " + "/".join(
        dict.fromkeys(c for c in destinations if c)
    )
    return full, short


def _travel_dates(trip: Trip, offer: FlightOffer | None, language: str) -> str:
    if offer is None:
        end = trip.return_date if trip.trip_type == "round_trip" else None
        return format_date_range(trip.depart_date, end, language)
    inbound = offer.inbound or {}
    end = offer.return_date or _parse_date(inbound.get("departure_time"))
    start = offer.depart_date or _parse_date(offer.departure_time)
    return format_date_range(start, end, language)


def _stops_text(stops: int | None, language: str) -> str:
    if stops is None:
        return ""
    if stops == 0:
        return _t(language, "nonstop")
    return _t(language, "one_stop") if stops == 1 else _t(language, "stops", n=stops)


def _leg_line(
    label: str,
    airline: str | None,
    flight_numbers: str | None,
    leg: dict[str, Any],
    language: str,
) -> str:
    """``"Outbound: Korean Air KE703 · ICN 09:05 → NRT 11:30 · nonstop"``."""
    carrier = " ".join(part for part in (airline, flight_numbers) if part)
    dep_time, arr_time = leg.get("departure_time"), leg.get("arrival_time")
    arrival = f"{leg.get('arrival_airport', '')} {_clock(arr_time)}".strip()
    dep_day, arr_day = _parse_date(dep_time), _parse_date(arr_time)
    if dep_day and arr_day and arr_day > dep_day:
        arrival += f"+{(arr_day - dep_day).days}"
    times = f"{leg.get('departure_airport', '')} {_clock(dep_time)}".strip() + f" → {arrival}"
    parts = [p for p in (carrier, times, _stops_text(leg.get("stops"), language)) if p]
    return f"{label}: " + " · ".join(parts)


def _provider_name(key: str) -> str:
    try:
        from app.providers.flights.registry import get_provider_class

        return get_provider_class(key).display_name
    except Exception:  # noqa: BLE001 - unknown/broken provider: fall back to the key
        return key.replace("_", " ").title()


def _outbound_stops(offer: FlightOffer) -> int | None:
    """Stops of the outbound leg alone; ``None`` when they cannot be known.

    ``FlightOffer.stops`` is the maximum over *both* legs (DESIGN §4), so it is only the
    outbound's count when there is no return leg or the return has fewer stops.
    """
    stored = (offer.outbound or {}).get("stops")
    if isinstance(stored, int):
        return stored
    overall = offer.stops
    inbound_stops = (offer.inbound or {}).get("stops")
    if overall is None or overall == 0 or not offer.inbound:  # max 0 -> both legs nonstop
        return overall
    if isinstance(inbound_stops, int) and inbound_stops < overall:
        return overall
    return None


def _outbound_leg(offer: FlightOffer) -> dict[str, Any]:
    """The stored outbound leg dict, gaps filled from the flattened (outbound) columns."""
    stored = offer.outbound or {}
    flattened = {
        "departure_airport": offer.departure_airport,
        "arrival_airport": offer.arrival_airport,
        "departure_time": offer.departure_time,
        "arrival_time": offer.arrival_time,
    }
    leg = {key: stored.get(key) or value for key, value in flattened.items()}
    leg["stops"] = _outbound_stops(offer)
    return leg


def _detail_lines(offer: FlightOffer | None, language: str) -> list[str]:
    if offer is None:
        return []
    outbound = _outbound_leg(offer)
    lines = [
        _leg_line(_t(language, "outbound"), offer.airline, offer.flight_number, outbound, language)
    ]
    inbound = offer.inbound or {}
    if inbound.get("departure_airport"):
        airlines = ", ".join(inbound.get("airlines") or [])
        numbers = " / ".join(inbound.get("flight_numbers") or [])
        lines.append(_leg_line(_t(language, "return"), airlines, numbers, inbound, language))
    source = _provider_name(offer.provider)
    if offer.seller and offer.seller.strip().lower() != source.lower():
        source = _t(language, "sold_by", source=source, seller=offer.seller.strip())
    lines.append(_t(language, "source", source=source))
    return lines


def _verdicts(facts: _AlertFacts, language: str) -> tuple[list[str], list[str]]:
    """(verdict sentences, short reasons), one per alert kind, in canonical order."""
    sentences: list[str] = []
    reasons: list[str] = []
    for kind in dict.fromkeys(event.kind for event in facts.events):
        if kind == "below_target":
            reached = (
                facts.price is not None
                and facts.target is not None
                and abs(facts.price - facts.target) < _EPSILON
            )
            sentences.append(_t(language, "at_target" if reached else "below_target"))
            reasons.append(_t(language, "reason_below_target"))
        elif kind == "price_drop":
            pct = _pct(facts.drop_percent or 0.0)
            sentences.append(_t(language, "price_drop", pct=pct))
            reasons.append(_t(language, "reason_price_drop", pct=pct))
        elif kind == "new_low":
            sentences.append(_t(language, "new_low"))
            reasons.append(_t(language, "reason_new_low"))
    return sentences, reasons


def _link(trip: Trip, offer: FlightOffer | None, language: str) -> tuple[str, str]:
    if offer is not None and offer.booking_url:
        return offer.booking_url, _t(language, "open_booking")
    if offer is not None and offer.source_url:
        return offer.source_url, _t(language, "open_search")
    return app_url(f"/trips/{trip.id}" if trip.id else "/"), _t(language, "open_app")


def format_price_alert(
    trip: Trip,
    run: SearchRun | None,
    best_offer: FlightOffer | None,
    events: Sequence[AlertEvent],
    language: Language | str = "en",
    *,
    previous_lowest: float | None = None,
) -> NotificationMessage:
    """One merged price-alert message for all ``events`` of a run (spec §8 layout).

    ``previous_lowest`` (display basis = ``trip.price_basis``) overrides the value carried by
    the events; the dispatcher passes it when no event knows it.
    """
    lang = language if language in TEXT else "en"
    facts = _AlertFacts(trip, run, best_offer, events, previous_lowest)
    route, short_route = _route_line(trip, best_offer, lang)
    dates = _travel_dates(trip, best_offer, lang)
    sentences, reasons = _verdicts(facts, lang)

    blocks = [route, f"{_t(lang, 'dates')}\n{dates}"]
    if facts.previous_lowest is not None:
        blocks.append(
            f"{_t(lang, 'previous_lowest')}\n{_amount_text(facts.previous_lowest, facts, lang)}"
        )
    if facts.price is not None:
        blocks.append(f"{_t(lang, 'current')}\n{_amount_text(facts.price, facts, lang)}")
    if facts.target is not None:
        blocks.append(f"{_t(lang, 'target')}\n{_amount_text(facts.target, facts, lang)}")
    if sentences:
        blocks.append("\n".join(sentences))
    details = _detail_lines(best_offer, lang)
    if details:
        blocks.append("\n".join(details))

    title = _t(lang, "alert_title")
    price_text = _amount_text(facts.price, facts, lang) if facts.price is not None else ""
    url, url_label = _link(trip, best_offer, lang)
    return NotificationMessage(
        title=title,
        body="\n\n".join(blocks),
        url=url,
        url_label=url_label,
        data=_alert_data(trip, run, best_offer, facts, reasons, lang)
        | {
            "route": route,
            "travel_dates": dates,
            "subject": _subject(title, short_route, facts, reasons),
            "summary": _summary(route, dates, price_text, facts, reasons, lang),
        },
    )


def _subject(title: str, short_route: str, facts: _AlertFacts, reasons: list[str]) -> str:
    price = format_amount(facts.price, facts.currency) if facts.price is not None else ""
    headline = f"{title}: {short_route} {price}".rstrip()
    return f"{headline} ({', '.join(reasons)})" if reasons else headline


def _summary(
    route: str,
    dates: str,
    price_text: str,
    facts: _AlertFacts,
    reasons: list[str],
    language: str,
) -> str:
    lines = [f"{route} · {dates}" if dates else route]
    price_parts = [_t(language, "now", price=price_text)] if price_text else []
    if facts.target is not None:
        target = format_amount(facts.target, facts.currency)
        price_parts.append(_t(language, "target_short", price=target))
    if price_parts:
        lines.append(" · ".join(price_parts))
    if reasons:
        reason_line = " · ".join(reasons)
        lines.append(reason_line[:1].upper() + reason_line[1:])
    return "\n".join(lines)


def _alert_data(
    trip: Trip,
    run: SearchRun | None,
    offer: FlightOffer | None,
    facts: _AlertFacts,
    reasons: list[str],
    language: str,
) -> dict[str, Any]:
    return {
        "kind": "price_alert",
        "language": language,
        "trip_id": trip.id,
        "run_id": run.id if run is not None else None,
        "offer_id": offer.id if offer is not None else None,
        "alert_kinds": list(dict.fromkeys(event.kind for event in facts.events)),
        "rule_ids": list(dict.fromkeys(event.rule_id for event in facts.events)),
        "reasons": reasons,
        "currency": facts.currency,
        "basis": facts.basis,
        "adults": facts.adults,
        "current_price": facts.price,
        "previous_lowest": facts.previous_lowest,
        "target_price": facts.target,
        "drop_percent": facts.drop_percent,
        "price_total": offer.price_total if offer is not None else None,
        "price_per_person": offer.price_per_person if offer is not None else None,
        "provider": offer.provider if offer is not None else None,
    }


