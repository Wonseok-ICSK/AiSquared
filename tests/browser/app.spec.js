test('live search displays retrieved fares, selected-flight links, and correct one-way inputs', async ({ page }) => {
  const data = JSON.parse(await readFile('tests/fixtures/google/round-trip-2.json', 'utf8'));
  const requests = [];
  await page.route('**/api/flights/search', async route => {
    const search = route.request().postDataJSON(); requests.push(search);
    await route.fulfill({ json: { search, offers: parseGoogleOffers(data, search).slice(0, 2), source: 'Google Flights', isDemo: false, checkedAt: new Date().toISOString() } });
  });
  await page.goto('/');
  await page.getByRole('button', { name: '실시간 항공권', exact: true }).click();
  await expect(page.getByRole('heading', { name: '지금 떠날 항공권을 찾아보세요.' })).toBeVisible();
  await page.getByLabel('출발일', { exact: true }).fill('2026-11-20');
  await page.getByLabel('귀국일', { exact: true }).fill('2026-11-27');
  await page.getByRole('button', { name: '실제 항공권 검색', exact: true }).click();
  await expect(page.getByText('실제 표시 요금', { exact: true })).toBeVisible();
  await expect(page.getByText('315,700원', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('YP 735', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '이 검색으로 모니터링' })).toBeEnabled();
  expect(requests[0].provider).toBe('google_flights'); expect(requests[0].passengers).toBe(2);
  const href = await page.getByRole('link', { name: '에어프레미아 날짜 넣고 항공권 검색', exact: true }).getAttribute('href');
  const payload = Buffer.from(new URL(href).searchParams.get('tfs'), 'base64url').toString('utf8');
  expect(payload).toContain('735'); expect(payload).toContain('2026-11-27');
  await page.screenshot({ path: 'test-results/screenshots/live-search-desktop.png', fullPage: true });
  await page.getByLabel('여행 종류').selectOption('one_way');
  await expect(page.getByLabel('귀국일', { exact: true })).toBeDisabled();
  await expect(page.locator('.live-results')).toHaveCount(0);
  await page.getByRole('button', { name: '실제 항공권 검색', exact: true }).click();
  await expect(page.locator('.live-results')).toBeVisible();
  expect(requests[1].returnDate).toBe(null); expect(requests[1].tripType).toBe('one_way');
});

