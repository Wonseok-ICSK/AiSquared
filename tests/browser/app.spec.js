test('desktop dashboard shows seeded trips, accessible fare history, flights, and the trip plan', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('lang', 'ko');
  await expect(page.getByRole('heading', { name: '다음 여행, 여기서 시작하세요.' })).toBeVisible();
  await expect(page.getByRole('button', { name: /도쿄, 더 가까이/ })).toBeVisible();
  await expect(page.getByRole('img', { name: /가격 기록/ })).toBeVisible();
  await page.screenshot({ path: 'test-results/screenshots/dashboard-desktop.png', fullPage: true });
  await page.getByRole('tab', { name: /일치 항공편/ }).click();
  await expect(page.getByText('제주항공', { exact: true }).first()).toBeVisible();
  await expect(page.getByText('날짜가 입력된 검색 화면에서 예약하세요.')).toBeVisible();
  const trips = await (await page.request.get('/api/trips')).json();
  const trip = await (await page.request.get(`/api/trips/${trips[0].id}`)).json();
  for (const airline of ['제주항공', '대한항공', '아시아나항공', '트리니티항공']) {
    const link = page.getByRole('link', { name: `${airline} 날짜 넣고 항공권 검색`, exact: true });
    await expect(link).toBeVisible();
    await expect(link).toHaveAttribute('target', '_blank');
    const url = new URL(await link.getAttribute('href'));
    expect(url.origin + url.pathname).toBe('https://www.google.com/travel/flights/search');
    expect(url.searchParams.has('q')).toBe(false);
    const payload = Buffer.from(url.searchParams.get('tfs'), 'base64url').toString('utf8');
    expect(payload).toContain('ICN'); expect(payload).toContain('NRT');
    expect(payload).toContain(trip.departureDate); expect(payload).toContain(trip.returnDate);
  }
  await expect(page.locator('.booking-conditions').first()).toContainText('성인 2명');
  await page.screenshot({ path: 'test-results/screenshots/flights-korean.png', fullPage: true });
  await page.getByRole('button', { name: '이 항공편으로 일정 만들기' }).first().click();
  await expect(page.getByRole('heading', { name: '나의 취향을 담은 여행.' })).toBeVisible();
  await expect(page.getByRole('tab', { name: /1일차/ })).toBeVisible();
  await page.getByRole('tab', { name: /2일차/ }).click();
  await expect(page.getByRole('tab', { name: /2일차/ })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: '알림 닫기' }).click();
  await page.screenshot({ path: 'test-results/screenshots/planner-desktop.png', fullPage: true });
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: '일정 내려받기' }).click();
  const exported = await download;
  expect(exported.suggestedFilename()).toContain('itinerary.md');
  const markdown = await readFile(await exported.path(), 'utf8');
  expect(markdown).toContain('## 1일차'); expect(markdown).toContain('예상 총액:');
  expect(markdown).toContain('공항 도착'); expect(markdown).not.toContain('Free time');
  expect(errors).toEqual([]);
});
